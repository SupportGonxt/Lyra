-- ADR-0131: a quote keeps the decomposition it was priced from.
--
-- The DIST finding of the 2026-10-01 sweep: both pricing paths compute a per-rule
-- breakdown (`rating.ts:110` for the table path, `dist-quoter.ts` for the carrier
-- path) and `runShop` rebuilt every row from an explicit field list with no
-- breakdown, into a table that had no column for one. So **the decomposition was
-- discarded at the single persistence point.**
--
-- For the table path it is reconstructible from `inputs_json` plus the offering's
-- `rating_table_json`. For the **carrier** path it is not reconstructible at all —
-- the underwriter's own line items (base rate, claims loading, policy fee) exist
-- nowhere else, so "why is this quote £412?" had no answer and never would.
--
-- Nullable, because a decline or an error has no decomposition, and a price of
-- nothing is not a breakdown of zeros.
ALTER TABLE `dist_quote_responses` ADD `breakdown_json` text;
